"""Explicit release operation. Build, packaging and startup never call this stamper."""
import argparse
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'plugin/framework'))
from app_version import assembly_version, canonical, timestamp


def stamp(display, utc, offset_minutes):
    padded, local = timestamp(display)
    if display != padded:
        raise ValueError('Stamp with the fully padded YY.MMDD.HHmmss display')
    instant = datetime.fromisoformat(utc.replace('Z', '+00:00'))
    if instant.tzinfo is None or instant.astimezone(timezone(timedelta(minutes=offset_minutes))).replace(tzinfo=None, microsecond=0) != local:
        raise ValueError('UTC instant and explicitly converted New York timestamp disagree')
    record = {'schema_version': 1, 'display_version': padded, 'package_version': canonical(padded),
              'assembly_version': assembly_version(padded), 'file_version': assembly_version(padded),
              'timezone': 'America/New_York', 'stamped_utc': instant.astimezone(timezone.utc).isoformat().replace('+00:00','Z')}
    old = {name: json.loads((ROOT/name).read_text(encoding='utf-8-sig')) for name in ('plugin/plugin.json', 'plugin/.codex-plugin/plugin.json')}
    prior = ROOT/'plugin/app-version.json'
    if prior.exists(): old['previous_stamp'] = json.loads(prior.read_bytes())
    mapping = ROOT/'.local/version-mappings'/f'{padded}.json'
    mapping.parent.mkdir(parents=True, exist_ok=True)
    if mapping.exists():
        if json.loads(mapping.read_bytes())['next'] != record:
            raise ValueError('This timestamp already identifies another checkpoint; preserve it and choose a new stamp')
    else: mapping.write_text(json.dumps({'previous':old,'next':record},indent=2)+'\n',encoding='utf-8')
    prior.write_text(json.dumps(record,indent=2)+'\n',encoding='utf-8')
    for name, value in old.items():
        if name == 'previous_stamp': continue
        value['version'] = record['package_version']
        (ROOT/name).write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')
    (ROOT/'build/AppVersion.props').write_text(f'''<Project>
  <!-- Generated by Stamp-AppVersion.ps1; never restamp during build/startup. -->
  <PropertyGroup>
    <AppDisplayVersion>{padded}</AppDisplayVersion>
    <AppPackageVersion>{record['package_version']}</AppPackageVersion>
    <Version>{record['package_version']}</Version>
    <PackageVersion>{record['package_version']}</PackageVersion>
    <AssemblyVersion>{record['assembly_version']}</AssemblyVersion>
    <FileVersion>{record['file_version']}</FileVersion>
    <InformationalVersion>{padded}</InformationalVersion>
    <IncludeSourceRevisionInInformationalVersion>false</IncludeSourceRevisionInInformationalVersion>
  </PropertyGroup>
</Project>
''',encoding='utf-8')
    (ROOT/'Shared/ReleaseStamp.cs').write_text(f'''// Generated by the explicit release stamper; do not generate at startup.
namespace SiemensMCPServer
{{
    internal static partial class AppRelease
    {{
        public const string DisplayVersion = "{padded}";
        public const string PackageVersion = "{record['package_version']}";
        public const string AssemblyVersion = "{record['assembly_version']}";
    }}
}}
''',encoding='utf-8')
    (ROOT/'Properties/ReleaseVersionInfo.cs').write_text(f'''// Desktop retains manual assembly metadata; identities share the fixed app stamp.
using System.Reflection;
[assembly: AssemblyVersion("{record['assembly_version']}")]
[assembly: AssemblyFileVersion("{record['file_version']}")]
[assembly: AssemblyInformationalVersion("{padded}")]
''',encoding='utf-8')
    print(json.dumps(record,indent=2))


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--display',required=True); parser.add_argument('--utc',required=True)
    parser.add_argument('--offset-minutes',required=True,type=int)
    args=parser.parse_args(); stamp(args.display,args.utc,args.offset_minutes)
